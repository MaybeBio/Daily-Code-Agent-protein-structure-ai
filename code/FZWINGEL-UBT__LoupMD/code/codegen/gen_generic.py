def _kernel_abi() -> int:
    text = (Path(__file__).resolve().parent.parent / "src" / "kernel_plugin.h").read_text(encoding="utf-8")
    return int(re.search(r"#define LOUP_KERNEL_ABI (\d+)", text).group(1))


def write_plugins(model_path: Path, out_dir: Path):
    """One kernel plugin source per product of ``model_path`` (src/kernel_plugin.h): the product's kernels as the
    library's generator emits them, and the two functions a plugin exports. Prints one line per product:
    ``plugin <signature> <lmax_out> <segments_w> <file>``, or ``skip <index> <shape>`` for a product outside the
    generic kernels' bounds."""
    _ensure_imports()
    from mace.cli.convert_e3nn_cueq import run as convert_e3nn_cueq

    from loupmd.export._fastmace import sc_factored, sc_generated

    model = torch.load(model_path, map_location="cpu", weights_only=False).float()
    out_dir.mkdir(parents=True, exist_ok=True)
    done = set()
    for idx, product in enumerate(convert_e3nn_cueq(model).products):
        sc = product.symmetric_contractions
        sh = sc_generated.shape_of(sc)
        if sh is None or sh[0] != 16 or sh[3] < PRODUCT_C_MIN or sh[3] > PRODUCT_C_MAX or sh[3] % 32 != 0:
            print(f"skip {idx} {sh}")
            continue
        prog, feats, _ = sc_factored.factor(sc_generated.merged_terms(sc.etp.polynomial), sh[0], sh[1], sh[2])
        sig = eg.product_signature(prog, feats, sh)
        if sig in done:
            continue
        done.add(sig)
        src, lo = emit_product(sig, prog, feats, sh)
        if lo == 0:  # as the library's own table (kGProd)
            ro = ", ".join(f"(const void*)gprod_{v}_fused_{sig}<{c}, {b}>" for v in ("ro1", "ro1s", "ro1c")
                           for c, b in ((128, 4), (256, 2), (512, 1)))
        else:
            ro = ", ".join(["nullptr"] * 9)
        text = "\n".join([
            "// Auto-generated by LoupMD/codegen/gen_generic.py --plugin. Do not edit.",
            f"// The product kernels of signature {sig} ({model_path.name}, product {idx}) as a kernel plugin.",
            '#include "generated_generic.cuh"',
            '#include "kernel_plugin.h"',
            "#include <cstring>",
            "",
            src,
            f'static const GProdKernels kPlugin = {{"{sig}", {lo}, {int(sh[1])}, (const void*)gprod_fwd_{sig}, '
            f"(const void*)gprod_bwd_{sig}, {ro}, (const void*)gprod_fwdc_{sig}, (const void*)gprod_bwdc_{sig}}};",
            "",
            'extern "C" int loup_kernel_abi() { return LOUP_KERNEL_ABI; }',
            'extern "C" const GProdKernels* loup_plugin_gprod(const char* sig) {',
            "    return std::strcmp(sig, kPlugin.sig) == 0 ? &kPlugin : nullptr;",
            "}",
        ]) + "\n"
        path = out_dir / f"loupmd-kernels-{sig}.cu"
        path.write_text(text, encoding="utf-8")
        print(f"plugin {sig} {lo} {int(sh[1])} {path}")


