"""A minimal implicit transfer operator (ITO) built on conditional flow matching.

The ITO learns the transition density p(x_{t+tau} | x_t, tau) from trajectory data.
A sample of x_{t+tau} is generated by integrating an ODE

    dz/ds = v_theta(z, s | x_t, tau),   s from 0 to 1,

starting from Gaussian noise z(0) ~ N(0, I). The velocity field v_theta is a small neural network.
"""

import math

import numpy as np
import torch
import torch.nn as nn


# --------------------------------------------------------------------------------------
# Data: pairs (x_t, x_{t+tau}, tau) drawn from trajectories
# --------------------------------------------------------------------------------------
class LaggedPairs:
    """Draws random training pairs (x_t, x_{t+tau}, tau) from a set of trajectories.

    Args:
        trajs: array (n_traj, n_frames, dim)
        max_lag: largest lag (in frames) to train on. Lags are drawn log-uniformly
            from 1, ..., max_lag so that short and long lags are equally represented.
    """

    def __init__(self, trajs, max_lag):
        self.trajs = torch.as_tensor(np.asarray(trajs), dtype=torch.float32)
        self.n_traj, self.n_frames, self.dim = self.trajs.shape
        assert max_lag < self.n_frames, "max_lag must be shorter than the trajectories"
        self.max_lag = max_lag

    def sample(self, batch_size):
        log_lag = torch.rand(batch_size) * math.log(self.max_lag + 1)
        lag = torch.exp(log_lag).long().clamp(1, self.max_lag)
        i = torch.randint(0, self.n_traj, (batch_size,))
        t = (torch.rand(batch_size) * (self.n_frames - lag)).long()
        return self.trajs[i, t], self.trajs[i, t + lag], lag


# --------------------------------------------------------------------------------------
# Model: the velocity field v_theta(z, s | x_t, tau)
# --------------------------------------------------------------------------------------
def fourier_features(u, n_freq):
    """Embed a scalar u (shape (B,)) as [sin(k u), cos(k u)] for k = 1..n_freq."""
    k = torch.arange(1, n_freq + 1, device=u.device, dtype=u.dtype)
    ku = u[:, None] * k[None, :] * math.pi
    return torch.cat([torch.sin(ku), torch.cos(ku)], dim=-1)


class VectorField(nn.Module):
    """MLP velocity field for flow matching, conditioned on the current state and the lag.

    Inputs: z (B, dim) the noisy sample, s (B,) the flow time in [0, 1],
            x_t (B, dim) the current state, lag (B,) the lag time in frames.
    Output: velocity (B, dim)
    """

    def __init__(self, dim=2, hidden=256, n_layers=4, n_freq=8, max_lag=500):
        super().__init__()
        self.config = dict(dim=dim, hidden=hidden, n_layers=n_layers, n_freq=n_freq, max_lag=max_lag)
        self.n_freq = n_freq
        self.log_max_lag = math.log(max_lag + 1)
        n_in = 2 * dim + 4 * n_freq  # z, x_t, embedding of s, embedding of log(lag)
        layers = [nn.Linear(n_in, hidden), nn.SiLU()]
        for _ in range(n_layers - 1):
            layers += [nn.Linear(hidden, hidden), nn.SiLU()]
        layers += [nn.Linear(hidden, dim)]
        self.net = nn.Sequential(*layers)

    def forward(self, z, s, x_t, lag):
        lag_feat = fourier_features(torch.log(lag.float()) / self.log_max_lag, self.n_freq)
        s_feat = fourier_features(s, self.n_freq)
        return self.net(torch.cat([z, x_t, s_feat, lag_feat], dim=-1))


# --------------------------------------------------------------------------------------
# Sampling: integrate the flow ODE, then roll out long trajectories
# --------------------------------------------------------------------------------------
@torch.no_grad()
def sample(model, x_t, lag, ode_steps=20):
    """Draw one sample x_{t+lag} ~ p(. | x_t, lag) for every row of x_t (Euler integration)."""
    x_t = torch.as_tensor(x_t, dtype=torch.float32)
    lag = torch.as_tensor(lag).long().expand(x_t.shape[0])
    z = torch.randn_like(x_t)
    ds = 1.0 / ode_steps
    for k in range(ode_steps):
        s = torch.full((x_t.shape[0],), k * ds)
        z = z + ds * model(z, s, x_t, lag)
    return z


@torch.no_grad()
def rollout(model, x0, lag, n_steps, ode_steps=20):
    """Generate trajectories by applying the learned transition density repeatedly.

    Returns an array (n_traj, n_steps + 1, dim); frames are `lag` frames apart.
    """
    x = torch.as_tensor(x0, dtype=torch.float32)
    frames = [x]
    for _ in range(n_steps):
        x = sample(model, x, lag, ode_steps)
        frames.append(x)
    return torch.stack(frames, dim=1).numpy()


def save_model(model, path, **extra):
    torch.save({"config": model.config, "state_dict": model.state_dict(), **extra}, path)


def load_model(path):
    ckpt = torch.load(path, map_location="cpu", weights_only=False)
    model = VectorField(**ckpt["config"])
    model.load_state_dict(ckpt["state_dict"])
    return model.eval(), ckpt
